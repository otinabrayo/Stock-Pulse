from datetime import datetime, timedelta
from airflow.sdk.exceptions import AirflowFailException
from airflow.providers.amazon.aws.hooks.s3 import S3Hook
from airflow.providers.standard.operators.bash import BashOperator
from airflow.sdk import DAG, get_current_context, task

default_args = {
    "owner": "stockpulse",
    "depends_on_past": False,
    "retries": 2,
    "retry_delay": timedelta(minutes=2),
}

DBT_DIR = "/opt/airflow/dbt-stock-pulse"

with DAG(
    dag_id="stockpulse_analytics",
    description="Fetch raw CSV from MinIO, then build and test StockPulse models",
    default_args=default_args,
    start_date=datetime(2026, 1, 1),
    schedule="0 2 * * *",
    catchup=False,
    max_active_runs=1,
    tags=["stockpulse", "dbt", "analytics"],
) as dag:

    check_database = BashOperator(
        task_id="check_database",
        bash_command=(
            "python -c \""
            "import os, psycopg2; "
            "conn = psycopg2.connect("
            "host='postgres', dbname='stockpulse', port=5432, "
            "user=os.environ['POSTGRES_USER'], "
            "password=os.environ['POSTGRES_PASSWORD']); "
            "conn.close(); "
            "print('PostgreSQL connection successful')\""
        ),
    )

    @task
    def fetch_raw_csv():
        conf = get_current_context()["dag_run"].conf or {}
        bucket = conf.get("bucket")
        key = conf.get("object_key")
        run_id = conf.get("ingestion_run_id")

        # Scheduled 02:00 runs have no conf, so there is no file to fetch.
        if not key:
            print("No object_key in conf (scheduled run). Skipping fetch.")
            return None

        hook = S3Hook(aws_conn_id="minio_s3")

        if not hook.check_for_key(key, bucket_name=bucket):
            raise AirflowFailException(f"s3://{bucket}/{key} not found in MinIO")

        local_path = hook.download_file(
            key=key,
            bucket_name=bucket,
            local_path="/tmp/stockpulse",
            preserve_file_name=True,
            use_autogenerated_subdir=False,
        )

        with open(local_path, encoding="utf-8-sig") as f:
            data_rows = sum(1 for _ in f) - 1  # minus header

        if data_rows <= 0:
            raise AirflowFailException("Raw CSV has no data rows")

        print(f"Run {run_id}: fetched {data_rows} rows from s3://{bucket}/{key}")
        return {"run_id": run_id, "rows": data_rows}

    run_dbt = BashOperator(
        task_id="run_dbt_models",
        bash_command=f"dbt run --project-dir {DBT_DIR} --profiles-dir {DBT_DIR}",
    )

    test_dbt = BashOperator(
        task_id="test_dbt_models",
        bash_command=f"dbt test --project-dir {DBT_DIR} --profiles-dir {DBT_DIR}",
    )

    check_database >> fetch_raw_csv() >> run_dbt >> test_dbt
